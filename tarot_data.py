def meaning_text(card: dict, upright: bool, *, brief: bool = False) -> str:
    """渲染一张牌的释义文本（数据层的唯一出口）。

    brief=True：只出关键词（顿号串）——卡面信息区两行约束，与旧版观感一致；
    brief=False：关键词 + 能量状态（逆位 energy）+ 走向（what）
                 + 心法/转身（how/turn），供本地文字兜底与 AI 解读素材；
                 空字段自动跳过。
    """
    side = card["up"] if upright else card["down"]
    kw = "、".join(side["keywords"])
    if brief:
        return kw
    energy = side.get("energy") or ""
    extra = side.get("what") or ""
    tail = side.get("how") or side.get("turn") or ""
    parts = [kw]
    if energy:
        parts.append(energy.rstrip("。！？!?"))
    if extra:
        parts.append(extra.rstrip("。！？!?"))
    if tail:
        parts.append(tail.rstrip("。！？!?"))
    return "。".join(parts)
