"""身份键的纯转义规则：只处理字符串，不碰事件对象。

事件字段的读取与两级降级在 adapters/event.py；这里只保证拼接单射。
"""


def escape_identity_part(part: str) -> str:
    """把平台 ID / 用户 ID 编成可安全拼进单键的片段。

    只转义 ``%`` 与 ``:``：前者是转义符本身，后者是分隔符。普通 ID（纯数字、
    ``qq`` / ``telegram`` 这类平台名）原样保留；含分隔符的 ID 变成 ``%3A``，
    拼接因此是单射——``p`` + ``x:y`` 与 ``p:x`` + ``y`` 不会再落到同一个身份上。
    """
    return part.replace("%", "%25").replace(":", "%3A")
