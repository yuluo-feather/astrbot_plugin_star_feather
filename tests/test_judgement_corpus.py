"""判定语料回归：帮助请求 / 每日牌运 两套判定的边界问法锁定。

设计初衷（2026-08-29）：运势这类「规则 vs 用户真实问法」的宽严 bug，
静态读代码看不出来——只有真实用户会怎么问、说什么会误触，这些信息只在对话里。
本文件把踩过的坑 + 常见变体 + 疑似漏网全部枚举锁定：任何一条误判直接挂。
以后改判定规则，先过这个清单再动笔。

期望值以「用户视角正确」为准（不是以现有代码为准）：语料先定期望，
实现不符合期望即为 bug，修实现而不是改期望。
"""
import pytest
from daily import _is_daily_request

from main import _HELP_REQUEST_RE, _HELP_USAGE_RE


def is_help(text: str) -> bool:
    """帮助判定入口：与 main._command_entry 保持一致（两个分支任一命中即算）。"""
    t = (text or "").strip()
    return bool(_HELP_REQUEST_RE.fullmatch(t) or _HELP_USAGE_RE.fullmatch(t))


# ---------- 每日牌运判定 ----------
class TestDailyJudgement:
    """_is_daily_request：明确运势词即算；泛时间词须无具体主题。"""

    @pytest.mark.parametrize("q", [
        # 明确运势词（含英文）
        "运势", "看看今天的运势", "今天运势", "今日运势",
        "我今天的运气怎么样", "daily luck", "本周运势", "下周运势",
        # 泛时间词 + 无主题
        "最近怎么样", "今天怎么样", "每日塔罗", "近期如何",
        # 修复项：泛时间词缺料（这个月/这两天/这段时间——不含「这周/本周」，
        # 它们与「这周六见面」类事件问法无法区分，宁可漏网不误伤，见 not_trigger）
        "这个月如何", "这两天怎么样", "这段时间还好吗",
        # 运势词 + 主题：仍算牌运（牌固定，解读按主题分缓存，见 _norm_topic）
        "今天感情运势",
    ])
    def test_trigger(self, q):
        assert _is_daily_request(q), f"应当判为每日牌运: {q!r}"

    @pytest.mark.parametrize("q", [
        # 泛时间词 + 具体主题：按具体问题选阵（v0.5.3 踩过的坑）
        "今天她理我吗",
        "最近她对我什么感觉",
        "我最近学业怎么样",
        "最近我的桃花",
        "今天工作如何",
        "最近我们的关系",
        "这个月考研如何",
        "我最近和同事的关系",
        # 主题词单独出现（他/她/我们/喜欢 等）不落入泛问
        "最近的他",
        "最近喜欢上了剧本杀",
        "今天的桃花运",
        # 观察项（锁定现状）：「这周/本周 + 无主题」与「这周六见面」类事件问法
        # 无法区分——宁可按具体问题走占卜，不扩词表引入新误伤
        "这周怎么样", "本周如何",
        # 无运势/时间词：普通占卜问题（含「明天」这类跨日时间词）
        "明天她理我吗",
        "他说明天来",
        "占卜",
    ])
    def test_not_trigger(self, q):
        assert not _is_daily_request(q), f"不应当判为每日牌运: {q!r}"

    def test_known_edge_has_fortune_word_is_daily(self):
        """已知边界（锁定现状）：「他有运气吗」命中的是 DAILY 词「运气」，
        落入今日牌运而非具体占卜——口语「运气」作宾语时无法与「运势查询」区分，
        收益 vs 规则复杂度不成比例，锁定不修。"""
        assert _is_daily_request("他有运气吗")

# ---------- 帮助请求判定 ----------
class TestHelpJudgement:
    """应判为「帮助」：整句剥掉祈使词后只剩 帮助/help/说明/怎么用 类核心词。"""

    @pytest.mark.parametrize("q", [
        # 基本形态
        "帮助", "help", "HELP", "帮助一下", "help一下", "说明",
        # 祈使前缀（请/帮我/来看/瞅瞅/查一下 等）
        "请帮助", "使用帮助", "看下说明", "帮我看看帮助说明", "麻烦说明一下",
        "查看帮助", "瞅瞅说明", "查一下使用说明", "来看下帮助", "使用说明",
        # 核心词与「一下」之间带空格（修复项：不加空白会漏掉「help 一下」）
        "help 一下", "帮助 一下",
        # 说/讲/告诉/教 等口语引导 + 功能意图词（高频问法，引导词枚举不现实，
        # 按「怎么用/怎么玩/怎么使用/怎么操作/用法」独立宽松判定）
        "说一下帮助", "讲下说明", "告诉你怎么用", "教我怎么玩",
        "怎么用", "怎么玩", "用法", "帮我看看怎么用", "请告诉用法",
        "怎么使用", "怎么操作", "这个怎么玩",
    ])
    def test_trigger(self, q):
        assert is_help(q), f"应当判为帮助请求: {q!r}"

    @pytest.mark.parametrize("q", [
        # 问题正文带「帮助」：走占卜不触发帮助页（v0.5.3 踩过的坑）
        "帮助我做出决定",
        "最近公司调岗，帮助我做出决定",
        "怎么帮助她",
        "帮助与背叛的关系",          # 「帮助」是占卜主题词，不是请求
        "我需要帮助",
        "help me decide",            # 英文整句是占卜问题
        "说一下帮助的事",            # 带了宾语，不是求说明
        "help 一下我吗",             # 疑问带主语，不是请求
        # 文档类不算（说明书/说明文档 不属于帮助页语义）
        "说明书", "说明文档",
        # 「说明」在句中作动词（他说明天来）不误伤
        "他说明天来",
        # 纯占卜问法
        "帮我占卜一下", "今天运势如何",
    ])
    def test_not_trigger(self, q):
        assert not is_help(q), f"不应当判为帮助请求: {q!r}"


class TestDailyEventAttribution:
    """第三层排除（2026-08-29）：事件归因式问法不判每日牌运，走自由随机。

    分类依据（非枚举）：「运势/运气」等词出现在因果连词（是因为/是不是因为/
    难道是因为/就是因为/可能因为）之后——此时「运势」是归因宾语（「事件是不是
    运势导致的」），不是被查询的运势值本身。真·运势查询的「运势」在句首/主题位
    （「今天运势为什么这么差」），不命中排除，维持固定牌运。
    """

    @pytest.mark.parametrize("q", [
        # 事件 + 因果连词 + 运势词在后 → 归因咨询
        "今天中午左手无名指指头被门夹了，是因为运势太差的原因吗",
        "最近总是睡不好，是不是因为运势不好",
        "我今天这么倒霉是不是因为运气差",
        "考试没考好难道是因为运势不行吗",
        "工资没涨大概是因为运气不太好",
    ])
    def test_event_attribution_not_daily(self, q):
        assert not _is_daily_request(q), f"事件归因式不应判为每日牌运: {q!r}"

    @pytest.mark.parametrize("q", [
        # 运势主题在前：真·运势查询，「是不是」是追问语气而非事件归因
        "今天运势为什么这么差",
        "我今天的运势是不是会变好",
        "明天运气不好怎么办",
        # 现有锁定不破坏
        "今天感情运势",
        "他有运气吗",
        "我今天的运气怎么样",
    ])
    def test_still_daily(self, q):
        assert _is_daily_request(q), f"仍是每日牌运: {q!r}"

